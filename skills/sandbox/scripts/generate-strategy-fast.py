def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a fast enterprise-sandbox strategy")
    parser.add_argument("--rules-source", required=True)
    parser.add_argument("--role", required=True, choices=("CEO", "财务", "生产", "人力"))
    parser.add_argument("--style", required=True, choices=("保守型", "激进型"))
    parser.add_argument("--makeup-market", required=True, choices=("是", "否"))
    parser.add_argument("--output", required=True)
    return parser.parse_args()


def clean_lines(text: str) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for raw in text.splitlines():
        line = re.sub(r"\s+", " ", raw).strip(" |\t")
        if not line or line.startswith(("[PAGE", "[TABLE", "[/TABLE", "[FILE")):
            continue
        if len(line) < 4:
            continue
        line = line[:220]
        key = line.casefold()
        if key in seen:
            continue
        seen.add(key)
        result.append(line)
    return result


def select_facts(lines: list[str]) -> dict[str, list[str]]:
    selected: dict[str, list[str]] = {}
    for name, keywords in CATEGORIES:
        matches = [line for line in lines if any(word.casefold() in line.casefold() for word in keywords)]
        selected[name] = matches[:10]
    return selected


def fact_block(facts: dict[str, list[str]], name: str) -> str:
    items = facts.get(name, [])
    if not items:
        return "- 规则原文中未稳定抽取到本模块的明确条款，以下建议按条件式执行，赛前需回到规则原件确认。"
    return "\n".join(f"- {item}" for item in items)


