def main() -> None:
    args = parse_args()
    source = Path(args.rules_source).expanduser().resolve()
    output = Path(args.output).expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(f"规则文本不存在：{source}")
    text = source.read_text(encoding="utf-8-sig", errors="replace")
    lines = clean_lines(text)
    strategy = build_strategy(lines, args.role, args.style, args.makeup_market)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(strategy, encoding="utf-8")
    print(f"{output}|chars={len(strategy)}|facts={len(lines)}")


if __name__ == "__main__":
    main()
